-- Create bufferpool
CALL rdsadmin.create_bufferpool('basdb','DBASBBP',1024,'Y','Y',32768,0,32);
CALL rdsadmin.create_bufferpool('basdb','DBASBBP32K',-1,'Y','Y',32768,0,32);

-- Create table spaces
CALL rdsadmin.create_tablespace('basdb','USRTMPSPC1','DBASBBP',32768,NULL,NULL,'T','AUTOMATIC');
CALL rdsadmin.create_tablespace('basdb','USERSPACE32K','DBASBBP32K',32768,NULL,NULL,'U','AUTOMATIC');

-- Create role for the database with the role name of BAS
CALL rdsadmin.create_role('basdb','BAS');
-- Create a user
CALL rdsadmin.add_user('<username>','<password>',null);
CALL rdsadmin.grant_role(?,'basdb','BAS','USER <username>','N');
CALL rdsadmin.update_db_param('basdb','LOGSECOND','64');
-- Need DATAACCESS to run the JDBC APIs inside DatabaseMetaData
CALL rdsadmin.dbadm_grant(?,'basdb','DATAACCESS','USER <username>');

